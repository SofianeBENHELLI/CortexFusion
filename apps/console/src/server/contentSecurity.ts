import type { Plugin } from "vite";

/** Policy for built bundles. Scripts, data and fonts come only from the console's
 * own origin; inline styles stay allowed for components that inject <style>. */
export const CONTENT_SECURITY_POLICY = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  "connect-src 'self'",
  "worker-src 'self' blob:",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
].join("; ");

/** Adds the policy to production HTML only; the dev server keeps Vite's inline client. */
export function contentSecurityPolicy(): Plugin {
  return {
    name: "openbrain-content-security-policy",
    apply: "build",
    transformIndexHtml() {
      return [
        {
          tag: "meta",
          attrs: {
            "http-equiv": "Content-Security-Policy",
            content: CONTENT_SECURITY_POLICY,
          },
          injectTo: "head-prepend",
        },
      ];
    },
  };
}
